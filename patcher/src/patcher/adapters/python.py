"""Python: bump vulnerable packages with the project's own tool (uv, poetry, pipenv, pip-tools), or by
editing pinned requirements files. The tool is detected per project dir unless the recipe sets it."""

from __future__ import annotations

import json
import re
import shlex
import tomllib
from pathlib import Path

from ..models import PythonEco
from ..planner import Bump
from ..proc import CommandError, run
from ..versions import try_parse
from .base import Change, Ctx, Failure, Result

MARKERS = (("uv", "uv.lock"), ("poetry", "poetry.lock"), ("pipenv", "Pipfile.lock"), ("pip-tools", "requirements.in"))
# run through `uvx --from <tool>==<version>`; versions were >= 14 days old when pinned (bump deliberately)
DEFAULT_TOOL_VERSIONS = {"poetry": "2.5.1", "pipenv": "2026.9.1", "pip-tools": "7.6.2"}


def norm(name: str) -> str:
    """PEP 503 normalized project name."""
    return re.sub(r"[-_.]+", "-", name).lower()


def detect_tool(d: Path) -> str | None:
    for tool, marker in MARKERS:
        if (d / marker).exists():
            return tool
    reqs = sorted(d.glob("requirements*.txt"))
    if any(compile_command(r) for r in reqs):
        return "pip-tools"  # compiled by pip-compile / `uv pip compile` from inputs elsewhere
    return "pip" if reqs else None


# the generating command, as pip-compile and `uv pip compile` record it in the output's header
_COMPILE_CMD = re.compile(r"^#\s+((?:uv pip compile|pip-compile)\s.*?)\s*$", re.M)
_COMPILE_PY = re.compile(r"^#.*autogenerated by pip-compile with Python (\d+\.\d+)", re.M)


def compile_command(txt: Path) -> list[str] | None:
    try:
        head = "".join(txt.read_text(errors="replace").splitlines(keepends=True)[:20])
    except OSError:
        return None
    m = _COMPILE_CMD.search(head)
    return shlex.split(m.group(1)) if m else None


def _dirs(src: Path, patterns: list[str]) -> list[str]:
    out: list[str] = []
    for pat in patterns:
        for p in sorted(src.glob(pat)) if any(c in pat for c in "*?[") else [src / pat]:
            if p.is_dir() and detect_tool(p):
                rel = p.relative_to(src).as_posix() or "."
                if rel not in out:
                    out.append(rel)
    return out


def apply(ctx: Ctx, eco: PythonEco) -> Result:
    res = Result()
    bumps = ctx.plan.for_ecosystem("python")
    dirs = _dirs(ctx.src, eco.dirs)
    for b in bumps:
        if b.dir not in dirs:
            res.failures.append(Failure("python", b.target, b.name, b.to, f"{b.dir!r} is not a Python project dir listed in python.dirs"))
    for d in dirs:
        mine = [b for b in bumps if b.dir == d]
        if not mine:
            continue
        cwd = ctx.src / d
        tool = detect_tool(cwd) if eco.tool == "auto" else eco.tool
        try:
            if tool == "uv":
                res.extend(_uv(ctx, cwd, mine))
            elif tool == "poetry":
                res.extend(_poetry(ctx, cwd, mine, _tool_version(eco, "poetry", cwd)))
            elif tool == "pipenv":
                res.extend(_pipenv(ctx, cwd, mine, _tool_version(eco, "pipenv", cwd)))
            elif tool == "pip-tools":
                res.extend(_pip_tools(ctx, cwd, mine, _tool_version(eco, "pip-tools", cwd)))
            else:
                res.extend(_pinned_requirements(ctx, cwd, mine))
        except CommandError as e:
            res.failures += [Failure("python", b.target, b.name, b.to, f"{tool} failed: {e.tail[-1500:]}") for b in mine]
    return res


def _tool_version(eco: PythonEco, tool: str, cwd: Path) -> str:
    if eco.toolVersion:
        return eco.toolVersion
    if tool == "poetry" and (cwd / "poetry.lock").exists():
        m = re.search(r"@generated by Poetry (\d+\.\d+\.\d+)", (cwd / "poetry.lock").read_text()[:500])
        if m:
            return m.group(1)  # same Poetry as upstream, so the lock format doesn't churn
    return DEFAULT_TOOL_VERSIONS[tool]


def _uvx(tool: str, version: str, *args: str) -> list[str]:
    package = {"pip-tools": "pip-tools"}.get(tool, tool)
    entry = {"pip-tools": "pip-compile"}.get(tool, tool)
    return ["uvx", "--from", f"{package}=={version}", entry, *args]


def _changes(mine: list[Bump], note: str = "") -> list[Change]:
    return [Change("python", b.target, b.name, b.installed, b.to, ", ".join(b.reasons) + (f"; {note}" if note else "")) for b in mine]


# --- uv ----------------------------------------------------------------------------------------


def _uv(ctx: Ctx, cwd: Path, mine: list[Bump]) -> Result:
    args = ["uv", "lock"]
    for b in mine:
        args += ["--upgrade-package", f"{b.name}=={b.to}"]
    run(args, cwd=cwd, env=ctx.env, log_file=ctx.log, capture=False)
    return _verify(Result(changes=_changes(mine)), mine, _locked_uv(cwd))


def _locked_uv(cwd: Path) -> dict[str, str]:
    data = tomllib.loads((cwd / "uv.lock").read_text())
    return {norm(p["name"]): p.get("version", "") for p in data.get("package", [])}


# --- poetry ------------------------------------------------------------------------------------


def _locked_poetry(cwd: Path) -> dict[str, str]:
    data = tomllib.loads((cwd / "poetry.lock").read_text())
    return {norm(p["name"]): p.get("version", "") for p in data.get("package", [])}


def _direct_deps(cwd: Path) -> set[str]:
    pyproject = cwd / "pyproject.toml"
    if not pyproject.exists():
        return set()
    data = tomllib.loads(pyproject.read_text())
    names = set()
    for spec in data.get("project", {}).get("dependencies", []):
        names.add(norm(re.split(r"[\s<>=!~\[;(]", spec, maxsplit=1)[0]))
    poetry = data.get("tool", {}).get("poetry", {})
    names |= {norm(n) for n in poetry.get("dependencies", {})}
    for group in poetry.get("group", {}).values():
        names |= {norm(n) for n in group.get("dependencies", {})}
    return names - {"python"}


def _poetry(ctx: Ctx, cwd: Path, mine: list[Bump], version: str) -> Result:
    res = Result()
    run(_uvx("poetry", version, "update", "--lock", *[b.name for b in mine]), cwd=cwd, env=ctx.env, log_file=ctx.log, capture=False)
    locked, direct = _locked_poetry(cwd), _direct_deps(cwd)
    for b in mine:
        if _at_least(locked.get(norm(b.name)), b.to):
            res.changes += _changes([b])
        elif norm(b.name) in direct:
            res.failures.append(Failure("python", b.target, b.name, b.to,
                                        f"needs-human: pyproject.toml's constraint on {b.name} doesn't allow {b.to}"))
        else:
            # transitive and held back by another package's range: an explicit lower bound is the only lever
            run(_uvx("poetry", version, "add", "--lock", f"{b.name}>={b.to}"), cwd=cwd, env=ctx.env, log_file=ctx.log, capture=False)
            res.changes += _changes([b], f"added explicit constraint {b.name}>={b.to}")
    return _verify(res, mine, _locked_poetry(cwd))


# --- pipenv ------------------------------------------------------------------------------------


def _locked_pipenv(cwd: Path) -> dict[str, str]:
    data = json.loads((cwd / "Pipfile.lock").read_text())
    out = {}
    for section in ("default", "develop"):
        for name, meta in (data.get(section) or {}).items():
            out[norm(name)] = str(meta.get("version", "")).lstrip("=")
    return out


def _pipenv(ctx: Ctx, cwd: Path, mine: list[Bump], version: str) -> Result:
    # `pipenv upgrade` updates Pipfile.lock for just these packages
    run(_uvx("pipenv", version, "upgrade", *[f"{b.name}>={b.to}" for b in mine]), cwd=cwd, env=ctx.env, log_file=ctx.log, capture=False)
    return _verify(Result(changes=_changes(mine)), mine, _locked_pipenv(cwd))


# --- pip-tools ---------------------------------------------------------------------------------


def _pip_tools(ctx: Ctx, cwd: Path, mine: list[Bump], version: str) -> Result:
    res = Result()
    by_target: dict[str, list[Bump]] = {}
    for b in mine:
        by_target.setdefault(Path(b.target).name, []).append(b)
    for txt_name, group in by_target.items():
        txt, src_in = cwd / txt_name, cwd / (Path(txt_name).stem + ".in")
        upgrades = [f"--upgrade-package={b.name}=={b.to}" for b in group]
        recorded = compile_command(txt)
        if recorded:
            # re-run exactly what generated the file (its inputs may be more than a sibling .in)
            args, where = _recompile(recorded, txt, version, upgrades)
            run(args, cwd=where, env=ctx.env, log_file=ctx.log, capture=False)
        elif src_in.exists():
            args = ["--quiet", "--output-file", txt_name] + upgrades
            if "--hash=" in txt.read_text():
                args.append("--generate-hashes")
            run(_uvx("pip-tools", version, *args, src_in.name), cwd=cwd, env=ctx.env, log_file=ctx.log, capture=False)
        else:
            res.extend(_pinned_requirements(ctx, cwd, group))  # a plain pinned file next to the .in files
            continue
        res.extend(_verify(Result(changes=_changes(group)), group, _pinned(txt)))
    return res


def _recompile(recorded: list[str], txt: Path, version: str, upgrades: list[str]) -> tuple[list[str], Path]:
    """(command, cwd) re-running a header-recorded compile with targeted upgrades only."""
    args = [a for a in recorded if a not in ("-U", "--upgrade")]  # never upgrade everything
    out = None
    for i, a in enumerate(args):
        if a in ("-o", "--output-file") and i + 1 < len(args):
            out = args[i + 1]
        elif a.startswith("--output-file="):
            out = a.split("=", 1)[1]
    where = txt.parent
    if out and txt.as_posix().endswith("/" + out.removeprefix("./")):
        where = Path(txt.as_posix()[: -len(out.removeprefix("./"))])  # paths in the header are relative to here
    if args[:3] == ["uv", "pip", "compile"]:
        return [*args, *upgrades], where
    m = _COMPILE_PY.search(txt.read_text(errors="replace")[:1000])
    uvx = ["uvx", *(["--python", m.group(1)] if m else []), "--from", f"pip-tools=={version}", "pip-compile"]
    return [*uvx, *args[1:], *upgrades], where


# --- pinned requirements -----------------------------------------------------------------------


_REQ = re.compile(r"^(?P<lead>\s*)(?P<name>[A-Za-z0-9][A-Za-z0-9._-]*)(?P<extras>\[[^\]]*\])?\s*==\s*(?P<ver>[^\s;#\\]+)(?P<rest>.*)$")


def _pinned(path: Path) -> dict[str, str]:
    out = {}
    for line in path.read_text().splitlines():
        m = _REQ.match(line)
        if m:
            out[norm(m.group("name"))] = m.group("ver")
    return out


# a requirement line without an exact pin: `name`, `name>=1.0`, `name[extra]~=1.2 ; python_version>"3.9"`
_LOOSE = re.compile(r"^(?P<lead>\s*)(?P<name>[A-Za-z0-9][A-Za-z0-9._-]*)(?P<extras>\[[^\]]*\])?\s*(?P<spec>(?:[<>!~]=?|===?)[^;#\\]*?)?"
                    r"\s*(?P<rest>(?:;[^#]*)?(?:#.*)?)$")


def _pinned_requirements(ctx: Ctx, cwd: Path, mine: list[Bump]) -> Result:
    """Exact pins are moved. A loose or missing requirement gets a lower bound (`name>=fixed`), the pip
    analogue of an npm override: the image's next build then can't resolve a vulnerable version."""
    res = Result()
    for b in mine:
        path = ctx.src / b.target
        if not path.exists():
            res.failures.append(Failure("python", b.target, b.name, b.to, "requirements file not found"))
            continue
        text = path.read_text()
        lines = text.splitlines(keepends=True)
        hit = False
        for i, line in enumerate(lines):
            m = _REQ.match(line.rstrip("\n"))
            if not m or norm(m.group("name")) != norm(b.name):
                continue
            hashed = "--hash=" in line or (line.rstrip().endswith("\\") and i + 1 < len(lines) and "--hash=" in lines[i + 1])
            if hashed:
                res.failures.append(Failure("python", b.target, b.name, b.to,
                                            "needs-human: hash-pinned requirement and no requirements.in to recompile from"))
                hit = True
                break
            lines[i] = f"{m.group('lead')}{m.group('name')}{m.group('extras') or ''}=={b.to}{m.group('rest')}" + ("\n" if line.endswith("\n") else "")
            res.changes += _changes([b])
            hit = True
        if not hit and "--hash=" in text:
            res.failures.append(Failure("python", b.target, b.name, b.to,
                                        "needs-human: hash-checked requirements file; an unhashed line would break --require-hashes"))
            hit = True
        if not hit:
            for i, line in enumerate(lines):
                m = _LOOSE.match(line.rstrip("\n"))
                if not m or norm(m.group("name")) != norm(b.name) or line.lstrip().startswith(("-", "#")):
                    continue
                spec = (m.group("spec") or "").strip()
                bounded = f"{spec},>={b.to}" if spec else f">={b.to}"
                rest = m.group("rest")
                lines[i] = (f"{m.group('lead')}{m.group('name')}{m.group('extras') or ''}{bounded}{' ' + rest if rest else ''}"
                            + ("\n" if line.endswith("\n") else ""))
                res.changes += _changes([b], f"lower bound added to the loose requirement ({spec or 'unversioned'})")
                hit = True
        if not hit:  # transitive: nothing names it, so add the bound on its own line
            if lines and not lines[-1].endswith("\n"):
                lines[-1] += "\n"
            lines.append(f"{b.name}>={b.to}  # patcher: {', '.join(b.reasons)[:120]}\n")
            res.changes += _changes([b], "transitive: lower bound added")
        path.write_text("".join(lines))
    return res


# --- shared ------------------------------------------------------------------------------------


def _at_least(locked: str | None, wanted: str) -> bool:
    a, b = try_parse("python", locked), try_parse("python", wanted)
    return bool(a and b and a >= b)


def _verify(res: Result, mine: list[Bump], locked: dict[str, str]) -> Result:
    """Keep only changes that really landed in the lock/requirements; report the rest."""
    landed = []
    for c in res.changes:
        got = locked.get(norm(c.name))
        if _at_least(got, c.new):
            if got and got != c.new:
                c.new = got  # the tool picked a newer allowed version
            landed.append(c)
        else:
            res.failures.append(Failure("python", c.target, c.name, c.new, f"still at {got or 'unknown'} after the update"))
    res.changes = landed
    return res
