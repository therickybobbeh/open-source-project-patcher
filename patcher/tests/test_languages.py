    assert python._direct_deps(tmp_path) == {"requests", "flask", "uvicorn"}
    assert python._tool_version(recipe(ecosystems=[{"type": "python"}]).ecosystems[0], "poetry", tmp_path) == "1.8.3"
    assert python.detect_tool(tmp_path) == "poetry"


