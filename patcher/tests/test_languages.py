def recipe(**kw) -> Recipe:
    base = {"name": "demo", "source": {"repo": "o/r", "lines": [{"tagPattern": "x"}]}}
    base.update(kw)
    return Recipe.model_validate(base)


def ctx(src: Path, plan: Plan | None = None) -> Ctx:
    return Ctx(src=src, recipe=recipe(), plan=plan or Plan(), env={}, log=src / "log.txt")


