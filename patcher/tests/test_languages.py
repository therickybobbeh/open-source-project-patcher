def test_detect_toolchain_and_ecosystems(tmp_path):
    (tmp_path / "go.mod").write_text("module x\n\ngo 1.26.10\n")
    (tmp_path / "ui").mkdir()
    (tmp_path / "ui" / "package.json").write_text(json.dumps({"engines": {"node": ">=20"}, "packageManager": "pnpm@11.9.0"}))
    (tmp_path / "ui" / "pnpm-lock.yaml").write_text("lockfileVersion: '9.0'\n")
    (tmp_path / "pom.xml").write_text("<project><properties><maven.compiler.release>21</maven.compiler.release></properties></project>")
    (tmp_path / "core").mkdir()
    (tmp_path / "core" / "pom.xml").write_text("<project/>")
    (tmp_path / "py").mkdir()
    (tmp_path / "py" / ".python-version").write_text("3.11.9\n")
    (tmp_path / "py" / "requirements.txt").write_text("requests==2.31.0\n")
    (tmp_path / "Dockerfile").write_text("FROM golang:1.26 AS build\nFROM alpine:3.24 AS controller\n")
    tc = detect.toolchain(tmp_path, node_dirs=["ui"], python_dirs=["py"])
    assert tc == {"go": "1.26", "node": "20", "pnpm": "11.9.0", "python": "3.11", "java": "temurin-21"}
    ecos = {e["type"]: e for e in detect.ecosystems(tmp_path)}
    assert ecos["gomod"]["dirs"] == ["."] and ecos["pnpm"]["dirs"] == ["ui"] and ecos["python"]["dirs"] == ["py"]
    assert ecos["maven"]["poms"] == ["pom.xml"]  # module poms are not reactor roots
    assert ecos["dockerfile"]["files"] == ["Dockerfile"]
    assert detect.dockerfile_targets(tmp_path / "Dockerfile") == ["build", "controller"]
    # recipe values win; only languages the recipe uses are filled
    r = recipe(toolchain={"go": "1.27"}, ecosystems=[{"type": "gomod"}, {"type": "pnpm", "dirs": ["ui"]}])
    eff = toolchain.effective(Toolchain(go="1.27"), r, tmp_path)
    assert (eff.go, eff.node, eff.pnpm, eff.java, eff.python) == ("1.27", "20", "11.9.0", None, None)


