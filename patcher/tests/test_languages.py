def test_gradle_catalog_forms(tmp_path):
    cat = tmp_path / "libs.versions.toml"
    cat.write_text('[versions]\njackson = "2.17.1"\nshared = "1.0.0"\n\n[libraries]\n'
                   'jackson-databind = { module = "com.fasterxml.jackson.core:jackson-databind", version.ref = "jackson" }\n'
                   'jackson-core = { module = "com.fasterxml.jackson.core:jackson-core", version.ref = "jackson" }\n'
                   'a = { module = "org.a:a", version.ref = "shared" }\n'
                   'b = { module = "org.b:b", version.ref = "shared" }\n'
                   'netty = "io.netty:netty-codec:4.1.117.Final"\n'
                   'guava = { group = "com.google.guava", name = "guava", version = "33.3.1-jre" }\n')
    assert gradle.bump_catalog(cat, "com.fasterxml.jackson.core:jackson-databind", "2.18.2")
    assert gradle.bump_catalog(cat, "io.netty:netty-codec", "4.1.118.Final")
    assert gradle.bump_catalog(cat, "com.google.guava:guava", "33.4.0-jre")
    assert not gradle.bump_catalog(cat, "org.a:a", "1.0.1")  # shared ref across groups -> constraint instead
    text = cat.read_text()
    assert 'jackson = "2.18.2"' in text and '"io.netty:netty-codec:4.1.118.Final"' in text and 'version = "33.4.0-jre"' in text
    assert 'shared = "1.0.0"' in text


def test_gradle_constraints_script_and_wiring(tmp_path):
    (tmp_path / "build.gradle.kts").write_text('plugins { java }\n')
    pins = [Bump("gradle", "build.gradle", "org.yaml:snakeyaml", "1.33", "2.0", "major", ["CVE-1"])]
    gradle.write_constraints(tmp_path, pins)
    gradle.wire_constraints(tmp_path)
    gradle.wire_constraints(tmp_path)  # idempotent
    script = (tmp_path / gradle.CONSTRAINTS).read_text()
    assert "'org.yaml:snakeyaml': ['2.0', 'CVE-1']," in script and "resolutionStrategy.eachDependency" in script
    assert "afterEvaluate" in script and "patcherOlder(current, min[0])" in script  # raise only, after plugin rules
    assert (tmp_path / "build.gradle.kts").read_text().count('apply(from = "gradle/patcher-constraints.gradle")') == 1


