def skips(*entries):
    return SkipFile.model_validate({"skips": [{"reason": "r", "owner": "o", **e} for e in entries]})


def test_skip_rendering_new_frameworks(tmp_path):
    sf = skips({"match": "tests/test_api.py::test_live"}, {"match": "slow and network"})
    py = render_skips("pytest", sf, tmp_path)
    assert py.args == "--deselect tests/test_api.py::test_live -k 'not ((slow and network))'"
    gr = render_skips("gradle", skips({"match": "com.example.*IT"}), tmp_path)
    assert gr.args.startswith("--init-script ") and "excludeTestsMatching 'com.example.*IT'" in Path(gr.file).read_text()
    js = render_skips("jest", skips({"match": "flaky"}, {"match": "x", "filter": "e2e/"}), tmp_path)
    assert js.args == "--testNamePattern '^(?!.*((?:flaky)))' --testPathIgnorePatterns e2e/"
    vt = render_skips("vitest", skips({"match": "flaky"}, {"match": "x", "filter": "e2e/**"}), tmp_path)
    assert "--exclude 'e2e/**'" in vt.args
    assert render_skips("mocha", skips({"match": "flaky"}), tmp_path).args == "--grep flaky --invert"


