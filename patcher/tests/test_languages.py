def test_image_derived_findings(tmp_path):
    from patcher.pipeline import image_derived

    def f(eco, name, ver, path, fixed="1.34", vid=None):
        return Finding("img", eco, eco, name, ver, fixed, vid or f"CVE-{name}", "HIGH", "fixed", pkg_path=path)

    after = ScanReport("img", findings=[
        f("jar", "org.yaml:snakeyaml", "1.33", "app/lib/snakeyaml-1.33.jar"),
        f("jar", "org.yaml:snakeyaml", "1.33", "app/lib/snakeyaml-1.33.jar", fixed="1.35", vid="CVE-2"),  # needs more
        f("jar", "com.x:seen", "1.0", "app/lib/seen-1.0.jar"),              # already in the source scan
        f("jar", "org.other:tool", "1.0", "opt/tool/lib/tool.jar"),        # not under ownBinaries
        f("python-pkg", "pip", "24.0", "usr/local/lib/python3.12/site-packages/pip-24.0.dist-info/METADATA"),
    ])
    img = ImageOutcome("app", "ref", None, None, after, own_binaries=["app/"])
    fs_after = ScanReport("src", packages=[Package("x", "gradle", "com.x:seen", "1.0", "1")])
    r = recipe(ecosystems=[{"type": "gradle", "dirs": ["."]}])
    out = image_derived(r, [img], fs_after, tmp_path)
    assert [(x.ecosystem, x.target, x.name) for x in out.findings] == [("gradle", "build.gradle", "org.yaml:snakeyaml")] * 2
    plan = build_plan(out, r)
    # one bump that fixes both CVEs
    assert [(b.ecosystem, b.name, b.to) for b in plan.bumps] == [("gradle", "org.yaml:snakeyaml", "1.35")]


def test_pip_compile_header_is_rerun_with_targeted_upgrades(tmp_path):
    reqs = tmp_path / "requirements"
    reqs.mkdir()
    (reqs / "base.in").write_text("flask\n")
    (reqs / "requirements.txt").write_text(
        "#\n# This file is autogenerated by pip-compile with Python 3.12\n# by the following command:\n#\n"
        "#    pip-compile --generate-hashes --upgrade --output-file=requirements/requirements.txt pyproject.toml requirements/base.in\n"
        "#\nflask==3.1.0 \\\n    --hash=sha256:abc\n")
    assert python.detect_tool(reqs) == "pip-tools"
    txt = reqs / "requirements.txt"
    args, where = python._recompile(python.compile_command(txt), txt, "7.6.2", ["--upgrade-package=flask==3.1.3"])
    assert where == tmp_path  # header paths are relative to the repo root here
    assert args == ["uvx", "--python", "3.12", "--from", "pip-tools==7.6.2", "pip-compile", "--generate-hashes",
                    "--output-file=requirements/requirements.txt", "pyproject.toml", "requirements/base.in",
                    "--upgrade-package=flask==3.1.3"]  # --upgrade (everything) dropped
    (tmp_path / "requirements.txt").write_text(
        "# This file was autogenerated by uv via the following command:\n#    uv pip compile pyproject.toml -o requirements.txt\n"
        "flask==3.1.0\n")
    args, where = python._recompile(python.compile_command(tmp_path / "requirements.txt"), tmp_path / "requirements.txt", "7.6.2",
                                    ["--upgrade-package=flask==3.1.3"])
    assert args == ["uv", "pip", "compile", "pyproject.toml", "-o", "requirements.txt", "--upgrade-package=flask==3.1.3"]
    assert where == tmp_path
    (tmp_path / "plain").mkdir()
    (tmp_path / "plain" / "requirements.txt").write_text("flask==3.1.0\n")
    assert python.detect_tool(tmp_path / "plain") == "pip"


